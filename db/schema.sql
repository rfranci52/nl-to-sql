-- ============================================================================
-- Data platform: schema
-- One Neon Postgres instance, one schema (namespace) per app.
-- Run this FIRST in the Neon SQL editor, then seed.sql, then roles.sql.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS pizza;   -- the interactive pizza-shop demo
CREATE SCHEMA IF NOT EXISTS leads;   -- the portfolio's contact / lead capture

-- ---------------------------------------------------------------------------
-- pizza app: menu, live inventory, customers, orders
-- ---------------------------------------------------------------------------

-- The menu is a fixed set of SKUs; each carries its own restock level, so
-- "more drinks than whole pies" is data, not hardcoded logic.
CREATE TABLE pizza.menu_items (
    id             INTEGER PRIMARY KEY,
    name           TEXT NOT NULL,
    category       TEXT NOT NULL,            -- Whole Pie | Slice | Wings | Drink | Side
    price          NUMERIC(6,2) NOT NULL,
    baseline_stock INTEGER NOT NULL          -- nightly restock target for this item
);

-- Current stock, decremented on each order. The nightly restock sets
-- quantity back to the item's baseline_stock. Sales are NOT touched.
CREATE TABLE pizza.inventory (
    menu_item_id INTEGER PRIMARY KEY REFERENCES pizza.menu_items(id),
    quantity     INTEGER NOT NULL CHECK (quantity >= 0)
);

CREATE TABLE pizza.customers (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    city        TEXT NOT NULL,
    joined_date DATE NOT NULL DEFAULT CURRENT_DATE
);

-- Orders persist (the sales ledger accumulates). A guest order appends here.
CREATE TABLE pizza.orders (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES pizza.customers(id),
    order_date  DATE NOT NULL DEFAULT CURRENT_DATE,
    status      TEXT NOT NULL DEFAULT 'Received',  -- Received | In Progress | Delivered | Cancelled
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now() -- when the order was placed (date and time of day)
);

CREATE TABLE pizza.order_items (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     INTEGER NOT NULL REFERENCES pizza.orders(id),
    menu_item_id INTEGER NOT NULL REFERENCES pizza.menu_items(id),
    quantity     INTEGER NOT NULL CHECK (quantity > 0)
);

CREATE INDEX ON pizza.orders (customer_id);
CREATE INDEX ON pizza.orders (order_date);
CREATE INDEX ON pizza.order_items (order_id);
CREATE INDEX ON pizza.order_items (menu_item_id);

-- ---------------------------------------------------------------------------
-- leads app: portfolio contact / lead capture
-- ---------------------------------------------------------------------------

CREATE TABLE leads.submissions (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    email      TEXT NOT NULL,
    message    TEXT NOT NULL,
    source     TEXT,                          -- which page / demo it came from
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ON leads.submissions (created_at);
