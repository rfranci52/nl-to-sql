"""Generate seed.sql for the pizza schema (deterministic).

Run:  python3 gen_seed.py   ->  writes seed.sql
Then paste seed.sql into the Neon SQL editor, after schema.sql.

The menu lives here as plain data; edit names, prices, categories, or
baseline stock and re-run to regenerate the seed.
"""

import random
from datetime import date, timedelta
from pathlib import Path

random.seed(7)  # deterministic output
OUT = Path(__file__).resolve().parent / "seed.sql"

# (name, category, price, baseline_stock): more of the fast/cheap items.
MENU = [
    ("Margherita Pie",      "Whole Pie", 18.00, 25),
    ("Pepperoni Pie",       "Whole Pie", 20.00, 25),
    ("Veggie Supreme Pie",  "Whole Pie", 22.00, 25),
    ("Meat Lovers Pie",     "Whole Pie", 24.00, 25),
    ("Hawaiian Pie",        "Whole Pie", 20.00, 25),
    ("BBQ Chicken Pie",     "Whole Pie", 22.00, 25),
    ("White Pie",           "Whole Pie", 21.00, 25),
    ("Buffalo Chicken Pie", "Whole Pie", 22.00, 25),
    ("Cheese Slice",        "Slice",      3.50, 80),
    ("Pepperoni Slice",     "Slice",      4.00, 80),
    ("Sicilian Slice",      "Slice",      4.50, 80),
    ("Buffalo Wings (6)",   "Wings",      8.00, 60),
    ("Buffalo Wings (12)",  "Wings",     15.00, 60),
    ("BBQ Wings (12)",      "Wings",     15.00, 60),
    ("Fountain Soda",       "Drink",      2.50, 100),
    ("Bottled Water",       "Drink",      2.00, 100),
    ("Iced Tea",            "Drink",      3.00, 100),
    ("Lemonade",            "Drink",      3.00, 100),
    ("Garlic Knots",        "Side",       5.00, 50),
    ("House Salad",         "Side",       7.00, 50),
]

FIRST = ["Maria", "James", "Aisha", "David", "Sofia", "Marcus", "Elena", "Tyrone",
         "Nina", "Carlos", "Grace", "Omar", "Lena", "Andre", "Priya", "Sam", "Jade",
         "Victor", "Rosa", "Kwame", "Hana", "Leo", "Fatima", "Dominic"]
LAST = ["Rivera", "Chen", "Okafor", "Nguyen", "Patel", "Rossi", "Silva", "Kim",
        "Johnson", "Diaz", "Ali", "Brooks", "Cohen", "Santos", "Reyes", "Walsh"]
CITIES = ["Brooklyn", "Queens", "Bronx", "Manhattan", "Newark", "Jersey City", "Yonkers", "Hoboken"]
STATUSES = ["Delivered", "Delivered", "Delivered", "Delivered", "In Progress", "Cancelled"]


def q(s: str) -> str:
    return s.replace("'", "''")


def values(rows):
    return ",\n".join(rows) + ";"


today = date.today()
out = ["-- seed.sql: GENERATED by gen_seed.py, deterministic (random.seed(7)).",
       "-- Run in Neon after schema.sql.", "BEGIN;", ""]

# menu_items
out.append("INSERT INTO pizza.menu_items (id, name, category, price, baseline_stock) VALUES")
out.append(values([f"  ({i}, '{q(n)}', '{q(c)}', {p:.2f}, {b})"
                   for i, (n, c, p, b) in enumerate(MENU, 1)]))
out.append("")

# inventory starts full (= baseline)
out.append("INSERT INTO pizza.inventory (menu_item_id, quantity) VALUES")
out.append(values([f"  ({i}, {b})" for i, (_, _, _, b) in enumerate(MENU, 1)]))
out.append("")

# customers
customers, used = [], set()
for i in range(1, 25):
    while True:
        name = f"{random.choice(FIRST)} {random.choice(LAST)}"
        if name not in used:
            used.add(name)
            break
    joined = today - timedelta(days=random.randint(30, 720))
    customers.append((i, name, random.choice(CITIES), joined.isoformat()))
out.append("INSERT INTO pizza.customers (id, name, city, joined_date) VALUES")
out.append(values([f"  ({i}, '{q(n)}', '{q(c)}', '{j}')" for i, n, c, j in customers]))
out.append("")

# orders + order_items
menu_ids = list(range(1, len(MENU) + 1))
orders, items, item_id = [], [], 1
for oid in range(1, 91):
    odate = today - timedelta(days=random.randint(0, 90))
    orders.append((oid, random.randint(1, 24), odate.isoformat(), random.choice(STATUSES)))
    for _ in range(random.randint(1, 3)):
        items.append((item_id, oid, random.choice(menu_ids), random.randint(1, 3)))
        item_id += 1
out.append("INSERT INTO pizza.orders (id, customer_id, order_date, status) VALUES")
out.append(values([f"  ({o}, {c}, '{d}', '{s}')" for o, c, d, s in orders]))
out.append("")
out.append("INSERT INTO pizza.order_items (id, order_id, menu_item_id, quantity) VALUES")
out.append(values([f"  ({it}, {o}, {m}, {qty})" for it, o, m, qty in items]))
out.append("")

# advance the identity sequences past the seeded rows so guest inserts get fresh ids
for tbl in ("customers", "orders", "order_items"):
    out.append(f"SELECT setval(pg_get_serial_sequence('pizza.{tbl}', 'id'), "
               f"(SELECT MAX(id) FROM pizza.{tbl}));")
out.append("COMMIT;")

OUT.write_text("\n".join(out) + "\n")
print(f"wrote {OUT.name}: {len(MENU)} menu items, {len(customers)} customers, "
      f"{len(orders)} orders, {len(items)} order_items")
